# Build a lookup that accepts full names or 2-letter abbreviations.
_STATE_LOOKUP = {**US_STATE_CODES}
for code in US_STATE_CODES.values():
    _STATE_LOOKUP[code.lower()] = code


def normalize_state(state_input: str) -> str | None:
    """
    Convert a US state name or 2-letter abbreviation to its 2-letter code.
    Returns None if the input is not recognized.
    """
    if not state_input:
        return None
    normalized = state_input.strip().lower()
    return _STATE_LOOKUP.get(normalized)
